/** 前台常見近形／近音錯字，搜尋時視為同一字。 */
const SCHOOL_SEARCH_VARIANT: Record<string, string> = {
 方: "芳",
 芳: "芳",
 芬: "芳",
 語: "雨",
 雨: "雨",
 加: "迦",
 迦: "迦",
 喬: "僑",
 僑: "僑",
 傒: "溪",
 溪: "溪",
 学: "學",
 學: "學",
 鋒: "鳳",
 鳳: "鳳",
 令: "翎",
 翎: "翎",
 眞: "真",
 真: "真",
}

/** 去掉標點空白，並把方／芳、語／雨等錯見字摺成同一鍵，方便寬鬆搜尋。 */
export function normalizeSchoolSearchKey(raw: string): string {
 const s = raw
  .normalize("NFKC")
  .trim()
  .toLowerCase()
  .replace(/[\s（）()﹝﹞【】[\]·・．.、，,／/-]/g, "")
  .replace(/玄圓|圓玄/g, "圓玄")
 let out = ""
 for (const ch of s) out += SCHOOL_SEARCH_VARIANT[ch] ?? ch
 return out
}

export function schoolNameMatchesQuery(name: string, query: string): boolean {
 const q = query.trim()
 if (!q) return true
 const hay = normalizeSchoolSearchKey(name)
 return q
  .split(/\s+/)
  .map(normalizeSchoolSearchKey)
  .filter(Boolean)
  .every((token) => hay.includes(token))
}

export type SchoolSelectOption = { value: string; label: string }

const EMPTY_SCHOOL_OPTION: SchoolSelectOption = { value: "", label: "請選擇學校" }

/** 全港中學 + 既有／目前校名，並在最頂提供空白項以便明確清走。 */
export function buildSchoolSelectOptions(
 extraSchools: readonly string[] = [],
 currentSchool = ""
): SchoolSelectOption[] {
 const extras = [...extraSchools, currentSchool].map((s) => s.trim()).filter(Boolean)
 const names = [...new Set([...HK_SECONDARY_SCHOOLS, ...extras])].sort((a, b) =>
  a.localeCompare(b, "zh-Hant")
 )
 return [EMPTY_SCHOOL_OPTION, ...names.map((s) => ({ value: s, label: s }))]
}

