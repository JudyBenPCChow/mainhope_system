def sql_str(s: str) -> str:
    return "'" + s.replace("'", "''") + "'"


def parse_time_slot(raw: str) -> tuple[str, str, str]:
    t = raw.replace("-", "–").strip()
    m = re.match(r"^(\d{2}:\d{2})–(\d{2}:\d{2})$", t)
    if not m:
        raise ValueError(f"bad time slot: {raw}")
    return t, m.group(1), m.group(2)


def course_base_from_full(code: str) -> str:
    # 2627-CHIS5001-C → CHIS5001
    m = re.match(r"^2627-([A-Z0-9]+)-[A-Z0-9]$", code)
    if not m:
        raise ValueError(code)
    return m.group(1)


def section_from_full(code: str) -> str:
    return code.rsplit("-", 1)[-1]


def class_id_for(code: str) -> str:
    return str(uuid.uuid5(NS, f"2627-missing-class:{code}"))


def schedule_dates(weekday: int) -> list[date]:
    out: list[date] = []
    d = START
    while d <= END:
        if d.weekday() == weekday and d not in CLOSURE_DATES:
            out.append(d)
        d += timedelta(days=1)
    return out


def load_csv_rows() -> dict[str, dict[str, str]]:
    with CSV_PATH.open(encoding="utf-8-sig") as f:
        rows = list(csv.DictReader(f))
    code_key = [k for k in rows[0] if "course_code" in k][0]
    return {r[code_key].strip(): r for r in rows}


def main() -> None:
    by_code = load_csv_rows()
    lines: list[str] = [
        "-- 2627 v3.6 missing classes + schedules",
        "-- Generated by scripts/import_2627_missing_classes.py",
        "begin;",
    ]
    report: dict = {"classes": [], "schedule_count": 0}

    for code in MISSING_CODES:
        row = by_code[code]
        base = course_base_from_full(code)
        section = section_from_full(code)
        teacher = TEACHERS[row["任教老師"].strip()]
        room = ROOMS[row["課室"].strip()]
        course_id = COURSE_BY_BASE[base]
        grade = GRADE_BY_BASE[base]
        time_slot, start_t, end_t = parse_time_slot(row["時段"])
        dow = row["星期"].strip()
        wd = WD_MAP[dow]
        cid = class_id_for(code)

        lines += [
            "",
            f"-- {code} {row['班別']}",
            "insert into public.classes (",
            "  id, subject, course_id, academic_year_id, section_code, course_code_full,",
            "  grade, day_of_week, time_slot, lesson_slots_per_session,",
            "  teacher_id, classroom_id, start_date, end_date, status",
            ") values (",
            f"  {sql_str(cid)}::uuid, {sql_str('中國語文')}, {sql_str(course_id)}::uuid,",
            f"  {sql_str(YEAR_ID)}::uuid, {sql_str(section)}, {sql_str(code)},",
            f"  array[{sql_str(grade[0])}]::text[], {sql_str(dow)}, {sql_str(time_slot)}, 1,",
            f"  {sql_str(teacher)}::uuid, {sql_str(room)}::uuid,",
            f"  date '2026-09-01', date '2027-06-30', '進行中'",
            ") on conflict (id) do nothing;",
        ]

        dates = schedule_dates(wd)
        session = 1
        for d in dates:
            sid = str(uuid.uuid5(NS, f"2627-missing-sched:{code}:{d.isoformat()}"))
            lines.append(
                "insert into public.schedules ("
                "id, class_id, teacher_id, classroom_id, scheduled_date, start_time, end_time, status, session_number"
                ") values ("
                f"{sql_str(sid)}::uuid, {sql_str(cid)}::uuid, {sql_str(teacher)}::uuid, {sql_str(room)}::uuid, "
                f"date {sql_str(d.isoformat())}, {sql_str(start_t)}, {sql_str(end_t)}, '預定', {session}"
                ") on conflict (id) do nothing;"
            )
            session += 1

        report["classes"].append({"code": code, "schedules": len(dates)})
        report["schedule_count"] += len(dates)

    lines.append("commit;")

    OUT_SQL.parent.mkdir(parents=True, exist_ok=True)
    OUT_SQL.write_text("\n".join(lines) + "\n", encoding="utf-8")
    OUT_REPORT.write_text(json.dumps(report, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    print(f"Wrote {OUT_SQL} ({len(MISSING_CODES)} classes, {report['schedule_count']} schedules)")


if __name__ == "__main__":
    main()
