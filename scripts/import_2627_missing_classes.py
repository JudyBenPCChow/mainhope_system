"""Generate SQL to import v3.6 timetable classes missing from production.

Compares docs/year/2627/timetable/versions/v3.6/2627_timetable_class_codes_v3.6.csv
against live `classes.course_code_full` for academic year 2627.

Usage (repo root):
  python3 scripts/import_2627_missing_classes.py
    → import-output/2627_missing_classes_insert.sql
    → import-output/2627_missing_classes_report.json
"""

